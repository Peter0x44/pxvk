#!/usr/bin/env python3
"""Generate src/runtime/stubs.cpp: one logging stub per unsupported export.

  gen-stubs.py [--cuda-include DIR]

The export names come from src/runtime/unsupported-exports.txt (one per
line), which this script only reads. CUDA driver entry points are __stdcall
on 32-bit Windows, so each stub must pop exactly the caller's argument bytes:
the sizes are taken from the prototypes in the CUDA toolkit headers (cuda.h
and the graphics-interop headers; default: %CUDA_PATH%\\include). Each stub
logs its name once and returns CUDA_ERROR_NOT_SUPPORTED.
"""
import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADERS = ["cuda.h", "cudaGL.h", "cudaD3D9.h", "cudaD3D10.h", "cudaD3D11.h"]
# Stack bytes of a parameter on 32-bit Windows where it is not 4: 64-bit
# integers and structs passed by value. Everything else (pointers, handles,
# enums, int, size_t, 32-bit CUdeviceptr, promoted char/short) is 4.
SIZES = {"CUtexObject": 8, "CUsurfObject": 8, "cuuint64_t": 8, "unsigned long long": 8, "long long": 8,
         "double": 8, "CUipcEventHandle": 64, "CUipcMemHandle": 64}
BY_VALUE_STRUCTS = {"CUipcEventHandle", "CUipcMemHandle"}


def prototypes(include):
    found = {}
    for header in HEADERS:
        text = (include / header).read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        for m in re.finditer(r"CUresult\s+CUDAAPI\s+(\w+)\s*\(([^;]*?)\)\s*;", text, re.S):
            found.setdefault(m.group(1), " ".join(m.group(2).split()))
    return found


def parameter_bytes(params):
    sizes = []
    for p in (q.strip() for q in params.split(",")):
        if p in ("", "void"):
            continue
        if "*" in p:
            sizes.append(4)
            continue
        type_name = " ".join(w for w in p.split()[:-1] if w != "const")
        if type_name in BY_VALUE_STRUCTS or (type_name not in SIZES and type_name.startswith("struct")):
            if type_name not in SIZES:
                sys.exit(f"unknown by-value struct parameter '{p}'")
        sizes.append(SIZES.get(type_name, 4))
    return sizes


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    default = Path(os.environ.get("CUDA_PATH", "")) / "include"
    parser.add_argument("--cuda-include", default=str(default))
    include = Path(parser.parse_args().cuda_include)
    protos = prototypes(include)
    names = [n.strip() for n in (ROOT / "src/runtime/unsupported-exports.txt").read_text().splitlines() if n.strip()]
    lines = [
        "// Generated by tools/gen-stubs.py from src/runtime/unsupported-exports.txt",
        "// and the CUDA toolkit headers. Do not edit.",
        "//",
        "// CUDA driver entry points are __stdcall: each stub declares parameters",
        "// of the real sizes so that it pops exactly the caller's arguments.",
        '#include "cuda_abi.h"',
        "",
        "#include <cstdint>",
        "",
        "void pxvk_log_unsupported(const char *name);",
        "",
        "namespace {",
        "struct Bytes64 {",
        "    unsigned char bytes[64];",
        "};",
        "} // namespace",
        "",
    ]
    types = {4: "std::uint32_t", 8: "std::uint64_t", 64: "Bytes64"}
    for name in names:
        key = name if name in protos else re.sub(r"_v\d$", "", name)
        if key not in protos:
            sys.exit(f"no prototype for {name} in {include}")
        sizes = parameter_bytes(protos[key])
        params = ", ".join(f"{types[size]}" for size in sizes) or "void"
        lines.append(f"// {sum(sizes)} bytes of arguments")
        lines.append(f"PXVK_EXPORT CUresult PXVK_CUDAAPI {name}({params})")
        lines.append("{")
        lines.append(f'    pxvk_log_unsupported("{name}");')
        lines.append("    return CUDA_ERROR_NOT_SUPPORTED;")
        lines.append("}")
    (ROOT / "src/runtime/stubs.cpp").write_text("\n".join(lines) + "\n", newline="\n")
    print(f"{len(names)} stubs")


if __name__ == "__main__":
    main()
